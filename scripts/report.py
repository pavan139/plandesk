"""Render evals/REPORT.md from the saved result files (no API calls)."""

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
RESULTS = ROOT / "evals" / "results"
ORDER = ["closed_book__gpt-5.4-mini", "naive_rag__gpt-5.4-mini", "full__gpt-5.4-mini", "full__gpt-5.4-nano"]
LABEL = {
    "closed_book": "Closed book (no retrieval)",
    "naive_rag": "Naive RAG (no year filter, no grounding guard)",
    "full": "PlanDesk (year-aware hybrid retrieval + verified-quote guard)",
}


def fmt(v, suffix=""):
    return "n/a" if v is None else f"{v}{suffix}"


def main() -> None:
    runs = {}
    for name in ORDER:
        p = RESULTS / f"{name}.json"
        if p.exists():
            runs[name] = json.loads(p.read_text())

    lines = [
        "# Evaluation report",
        "",
        "Generated by `scripts/report.py` from `evals/results/*.json`. "
        "42 hand-written questions: 35 answerable from IRS Pubs 590-A, 590-B and 560 "
        "(2024 and 2025 editions), 7 that the publications cannot answer. Scoring is "
        "deterministic string matching against the source, with no LLM judge.",
        "",
        "| System | Model | Correct (answerable) | Supported by cited quote | Wrongly refused | Refused when it should (7) | p50 latency | Tokens/query |",
        "| --- | --- | ---: | ---: | ---: | ---: | ---: | ---: |",
    ]
    for name, data in runs.items():
        s = data["summary"]
        lines.append(
            f"| {LABEL[s['mode']]} | {s['model']} | {fmt(s['answer_accuracy_pct'], '%')} | "
            f"{fmt(s['supported_by_citation_pct'], '%') if s['mode'] != 'closed_book' else 'n/a'} | "
            f"{fmt(s['false_abstention_pct'], '%')} | {fmt(s['abstention_recall_pct'], '%')} | "
            f"{fmt(s['latency_p50_s'], ' s')} | {fmt(s['tokens_per_query_mean'])} |"
        )

    lines += ["", "## Accuracy by question type", "",
              "| System | Model | " + " | ".join(["limit", "year_trap", "next_year", "rule", "abstain"]) + " |",
              "| --- | --- | ---: | ---: | ---: | ---: | ---: |"]
    for name, data in runs.items():
        s = data["summary"]
        c = s["accuracy_by_category_pct"]
        lines.append(f"| {s['mode']} | {s['model']} | " + " | ".join(
            fmt(c.get(k), "%") for k in ["limit", "year_trap", "next_year", "rule", "abstain"]) + " |")

    lines += ["", "## Every miss", ""]
    for name, data in runs.items():
        misses = [
            (r, res) for r, res in zip(data["rows"], data["results"])
            if not r["correct"] or r["supported"] is False
        ]
        lines.append(f"### {name} ({len(misses)})")
        lines.append("")
        for r, res in misses:
            why = "refused" if res["abstained"] else ("wrong answer" if not r["correct"] else "right answer, no single cited quote states it")
            ans = res["answer"].replace("\n", " ").replace("|", "/")
            lines.append(f"- `{r['id']}` ({why}): {ans[:220]}")
        lines.append("")

    (ROOT / "evals" / "REPORT.md").write_text("\n".join(lines))
    print("\n".join(lines[:12]))


if __name__ == "__main__":
    main()
